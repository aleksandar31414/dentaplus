/**
 * Service 1: access to our own REST API (/api).
 * Attaches the JWT, parses JSON and converts error responses into ApiError.
 */
import { User, Dentist, Service, Appointment, Review, Record, Activity, toPage } from '../models';

export const TOKEN_KEY = 'dentaplus-token';

export class ApiError extends Error {
  constructor(status, message, errors) {
    super(message);
    this.status = status;
    this.errors = errors || {};
  }
}

const qs = (params = {}) => {
  const clean = Object.entries(params).filter(([, v]) => v !== undefined && v !== null && v !== '');
  return clean.length ? `?${new URLSearchParams(clean).toString()}` : '';
};

class ApiService {
  constructor(base = '/api') {
    this.base = base;
  }

  get token() {
    try { return localStorage.getItem(TOKEN_KEY); } catch { return null; }
  }

  async request(method, url, body, { raw = false } = {}) {
    const headers = { Accept: 'application/json' };
    if (body !== undefined) headers['Content-Type'] = 'application/json';
    if (this.token) headers.Authorization = `Bearer ${this.token}`;

    let res;
    try {
      res = await fetch(this.base + url, { method, headers, body: body !== undefined ? JSON.stringify(body) : undefined });
    } catch {
      throw new ApiError(0, 'Серверот не е достапен. Проверете ја врската.');
    }
    if (res.status === 401 && this.token) window.dispatchEvent(new Event('auth:expired'));
    if (raw && res.ok) return res;
    if (res.status === 204) return null;
    const data = await res.json().catch(() => ({}));
    if (!res.ok) throw new ApiError(res.status, data.message || `Грешка ${res.status}`, data.errors);
    return data;
  }

  get(url) { return this.request('GET', url); }
  post(url, body) { return this.request('POST', url, body ?? {}); }
  put(url, body) { return this.request('PUT', url, body); }
  delete(url) { return this.request('DELETE', url); }

  /** downloads a CSV report generated by the server */
  async download(url, filename) {
    const res = await this.request('GET', url, undefined, { raw: true });
    const blob = await res.blob();
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = filename;
    a.click();
    setTimeout(() => URL.revokeObjectURL(a.href), 1000);
  }

  // ---------- auth ----------
  login(email, password) { return this.post('/auth/login', { email, password }); }
  register(data) { return this.post('/auth/register', data); }
  me() { return this.get('/auth/me').then((u) => new User(u)); }

  // ---------- users ----------
  getUsers() { return this.get('/users').then((l) => l.map((u) => new User(u))); }
  updateUser(id, data) { return this.put(`/users/${id}`, data).then((u) => new User(u)); }
  deleteUser(id) { return this.delete(`/users/${id}`); }

  // ---------- dentists ----------
  getDentists(params) { return this.get(`/dentists${qs(params)}`).then((l) => l.map((d) => new Dentist(d))); }
  getDentist(id) { return this.get(`/dentists/${id}`).then((d) => new Dentist(d)); }
  getSlots(dentistId, date, serviceId) { return this.get(`/dentists/${dentistId}/slots${qs({ date, service: serviceId })}`); }
  saveDentist(d) {
    return (d._id ? this.put(`/dentists/${d._id}`, d.toPayload()) : this.post('/dentists', d.toPayload())).then((x) => new Dentist(x));
  }
  deleteDentist(id) { return this.delete(`/dentists/${id}`); }

  // ---------- services ----------
  getServices(params) { return this.get(`/services${qs(params)}`).then((l) => l.map((x) => new Service(x))); }
  getService(id) { return this.get(`/services/${id}`).then((x) => new Service(x)); }
  saveService(svc) {
    return (svc._id ? this.put(`/services/${svc._id}`, svc.toPayload()) : this.post('/services', svc.toPayload())).then((x) => new Service(x));
  }
  deleteService(id) { return this.delete(`/services/${id}`); }

  // ---------- appointments ----------
  getAppointments(params) { return this.get(`/appointments${qs(params)}`).then((p) => toPage(p, Appointment)); }
  getAppointment(id) { return this.get(`/appointments/${id}`).then((a) => new Appointment(a)); }
  book(data) { return this.post('/appointments', data).then((a) => new Appointment(a)); }
  cancelAppointment(id, reason) { return this.put(`/appointments/${id}/cancel`, { reason }).then((a) => new Appointment(a)); }
  setAppointmentStatus(id, status, extra = {}) { return this.put(`/appointments/${id}/status`, { status, ...extra }).then((a) => new Appointment(a)); }
  deleteAppointment(id) { return this.delete(`/appointments/${id}`); }
  downloadAppointmentsCsv(params) {
    return this.download(`/appointments/export.csv${qs(params)}`, `dentaplus-termini-${new Date().toISOString().slice(0, 10)}.csv`);
  }

  // ---------- reviews ----------
  getReviews(params) { return this.get(`/reviews${qs(params)}`).then((p) => toPage(p, Review)); }
  addReview(data) { return this.post('/reviews', data).then((r) => new Review(r)); }
  updateReview(id, data) { return this.put(`/reviews/${id}`, data).then((r) => new Review(r)); }
  deleteReview(id) { return this.delete(`/reviews/${id}`); }
  replyReview(id, reply) { return this.put(`/reviews/${id}/reply`, { reply }).then((r) => new Review(r)); }

  // ---------- dental record ----------
  getRecords(patient) { return this.get(`/records${qs({ patient })}`).then((l) => l.map((r) => new Record(r))); }
  addRecord(data) { return this.post('/records', data).then((r) => new Record(r)); }
  deleteRecord(id) { return this.delete(`/records/${id}`); }

  // ---------- activities / stats / db ----------
  getActivities(params) { return this.get(`/activities${qs(params)}`).then((p) => toPage(p, Activity)); }
  getOverview() { return this.get('/stats/overview'); }
  dbStatus() { return this.get('/db'); }
  dbClear() { return this.delete('/db'); }
  dbSeed() { return this.post('/db/seed'); }
}

export const api = new ApiService();
export default api;
